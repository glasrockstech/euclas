import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { Ajv } from 'ajv';
import { compile } from 'json-schema-to-typescript';
import type { JSONSchema } from 'json-schema-to-typescript';
import { readCanonical, canonicalDirectory } from './canonical.ts';
import { declarationProjection } from './projection.ts';
import { createRegistry, isObject } from '../src/registry.ts';
import { schemaRoots } from '../src/resources.ts';

const check = process.argv.slice(2);
if (check.some(argument => argument !== '--check') || check.length > 1) throw new Error('Usage: generate.ts [--check]');
const inputs = await readCanonical();
createRegistry(inputs);
const projection: unknown = declarationProjection(inputs);
const meta = new Ajv();
function isGeneratorInput(value: unknown): value is JSONSchema {
  return isObject(value) && meta.validateSchema(value) === true;
}
if (!isGeneratorInput(projection)) throw new Error(`Invalid structural projection: ${meta.errorsText()}`);
const header = '// Generated by contracts:generate. Structural types do not authenticate or authorize.\n';
const types = await compile(projection, 'ContractTypes', {
  bannerComment: header.trimEnd(), unknownAny: true,
  $refOptions: { resolve: { http: false, file: false } },
});
const lifecycle: unknown = JSON.parse(await readFile(new URL('lifecycle.json', canonicalDirectory), 'utf8'));
const deployment: unknown = JSON.parse(await readFile(new URL('deployment-lifecycle.json', canonicalDirectory), 'utf8'));
if (!isObject(lifecycle) || !isObject(deployment)) throw new Error('Expected lifecycle data objects');
const data = `${header}import type { ResourceInput, JsonObject } from '../registry.ts';
import type { ContractTypes } from './types.ts';
export const resources: readonly ResourceInput[] = ${JSON.stringify(inputs, null, 2)};
export const contractNames: readonly (keyof ContractTypes)[] = ${JSON.stringify(inputs.flatMap(schemaRoots).sort(), null, 2)};
export const lifecycle: JsonObject = ${JSON.stringify(lifecycle, null, 2)};
export const deploymentLifecycle: JsonObject = ${JSON.stringify(deployment, null, 2)};
`;
const outputs = new Map([['types.ts', types], ['data.ts', data]]);
const directory = new URL('../src/generated/', import.meta.url);
if (check.length) {
  const actual = (await readdir(directory)).sort();
  if (JSON.stringify(actual) !== JSON.stringify([...outputs.keys()].sort())) throw new Error('Generated file inventory drift');
  for (const [name, expected] of outputs) {
    if (await readFile(new URL(name, directory), 'utf8') !== expected) throw new Error(`Generated contract drift: ${name}`);
  }
  console.log(`Checked ${String(inputs.flatMap(schemaRoots).length)} roots; no files changed`);
} else {
  await mkdir(directory, { recursive: true });
  for (const [name, content] of outputs) await writeFile(new URL(name, directory), content);
  console.log(`Generated ${String(inputs.flatMap(schemaRoots).length)} roots`);
}
